test('a reused native bond lot ID cannot redirect a recorded sale to a different purchase', async () => {
  const text = gunzipSync(readFileSync('docs/playtests/core-mvp-b18-multi-course/browser-390-trades.json.gz')).toString()
  const source = parseHistory(text), work = new WorkBudget(options())
  const replay = await replayHistory(source, work, 13)
  assert(replay.before)
  let state = transact(replay.before, { kind: 'buy', asset: 'bonds', issuerId: 'an-tam', amount: 2_000_000 })
  let sold = false
  function sellFirstLot() {
    if (!sold && state.phase === 'rebalancing' && state.lap === 1) {
      const lot = creditBondLots(state).find(item => item.lot.id === 'bond-1')!
      assert(lot.quote.executable)
      state = transact(state, { kind: 'sell', asset: 'bonds', amount: lot.quote.available, lotId: lot.lot.id })
      sold = true
    }
  }
  for (const command of replay.commands.filter(entry => entry.sequence > 13)) {
    for (let i = 0; state.phase !== command.before.phase || state.lap !== command.before.lap; i++) {
      assert(i < 4)
      sellFirstLot()
      state = advance(state)
      sellFirstLot()
    }
    state = applyRecorded(state, command, work)
  }
  while (state.phase !== 'finished') state = advance(state)
  assert(sold)
  const actual = serializeLog(state)
  const handle = await createDecisionReplay(actual, { kind: 'bonds', decisionId: 'bonds:10', alternativeId: 'skip', lap: 1, turn: 3 }, options())
  assert.equal(handle.result.status, 'blocked')
  assert.match('reason' in handle.result ? handle.result.reason : '', /bond-lot-origin-mismatch/)
  assert.equal('comparison' in handle.result, false)
  handle.dispose()
})

test('native guards reject insufficient cash, defaulted issuer, unowned business upgrade and duplicate Advanced', async () => {
  for (const kind of ['stocks', 'bonds', 'business'] as const) {
    const source = parseHistory(multiAssetFixture(kind, 'skip'))
    const adapter = adapterFor(kind), entry = source.entries.find(adapter.matches)!
    const replay = await replayHistory(source, new WorkBudget(options()), entry.sequence)
    assert(replay.before)
    const immutable = JSON.stringify(replay.before)
    const before = structuredClone(replay.before)
    before.portfolio.cash = 0
    const purchase = adapter.alternatives(before, entry).find(option => option.id.startsWith('buy-'))!
    assert.throws(() => forkDecision(adapter, before, entry, purchase, new WorkBudget()))
    if (kind === 'bonds') {
      const defaulted = structuredClone(replay.before)
      defaulted.bondCredit!.issuers.find(issuer => issuer.id === 'an-tam')!.status = 'defaulted'
      const invalid = adapter.alternatives(defaulted, entry).find(option => option.id === 'buy-bonds:an-tam')!
      assert.throws(() => forkDecision(adapter, defaulted, entry, invalid, new WorkBudget()))
    }
    if (kind === 'business') {
      const locked = adapter.alternatives(replay.before, entry).find(option => option.id === 'upgrade-business:budget')!
      assert.throws(() => forkDecision(adapter, replay.before!, entry, locked, new WorkBudget()))
    }
    assert.equal(JSON.stringify(replay.before), immutable)
  }
  const text = gunzipSync(readFileSync('docs/playtests/core-mvp-b18-multi-course/browser-390-trades.json.gz')).toString()
  const entry = parseHistory(text).entries[53]
  const handle = await createDecisionReplay(text, { kind: 'advanced', decisionId: 'advanced:54', alternativeId: 'course-advanced', lap: entry.lap, turn: entry.turn }, options())
  assert.equal(handle.result.status, 'blocked')
  assert.equal('reason' in handle.result ? handle.result.reason : '', 'adapter-alternative-illegal')
  assert.equal('comparison' in handle.result, false)
  handle.dispose()
})
