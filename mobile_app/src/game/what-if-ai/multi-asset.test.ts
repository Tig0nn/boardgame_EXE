const options = () => ({ maxMilliseconds: 30_000 })
const pinnedCash = { stocks: -931_189, bonds: -108_679, business: 2_956_855, advanced: 8_000_000 }
for (const kind of ['stocks', 'bonds', 'business', 'advanced'] as const) {
  test(kind + ' independent native fixture requires explicit safe follow-ups and verifies a completed comparison without changing save', async () => {
    const text = multiAssetFixture(kind), source = parseHistory(text)
    const before = JSON.stringify(source.state)
    let save = '', after = ''
    assert(saveGameLocally(source.state, { setItem: (_key, value) => { save = value } }))
    const catalog = await listDecisionChoices(text, kind, options())
    const choice = catalog[0]
    assert(choice)
    const handle = await createDecisionReplay(text, choice, options())
    let result = handle.result, count = 0
    while (result.status === 'needs-followup') {
      assert(++count <= 8)
      assert.equal('comparison' in result, false)
      assert.deepEqual(result.followUp.options.map(option => option.id), ['skip'])
      const pending = result
      assert.equal((await handle.resume({ id: 'foreign', optionId: 'skip' }, options())).status, 'blocked')
      assert.deepEqual(handle.result, pending)
      result = await handle.resume({ id: result.followUp.id, optionId: 'skip' }, options())
    }
    assert.equal(result.status, 'supported-final', 'reason' in result ? result.reason : 'comparison required')
    assert(count > 0)
    assert.equal(result.comparison.lap, 4)
    assert(result.comparison.proof.actualReplay && result.comparison.proof.alternativeReplay && result.comparison.proof.sourceUnchanged)
    for (const metric of ['cash', 'totalWorth', 'liquidatableFunds'] as const) assert.equal(result.comparison.delta[metric], pinnedCash[kind])
    assert.equal(JSON.stringify(source.state), before)
    assert(saveGameLocally(source.state, { setItem: (_key, value) => { after = value } }))
    assert.equal(after, save)
    handle.dispose()
    assert.equal('comparison' in handle.result, false)
  })

  test(kind + ' rejects a forged alternative and a corrupted source before numeric publication', async () => {
    const text = multiAssetFixture(kind), catalog = await listDecisionChoices(text, kind, options())
    for (const [history, choice] of [[text, { ...catalog[0], alternativeId: 'deposit-one-start' as const }],
      [text.replace('EG3-AI-04-', 'tampered-'), catalog[0]]] as const) {
      const handle = await createDecisionReplay(history, choice, options())
      assert.equal(handle.result.status, 'blocked')
      assert.equal('comparison' in handle.result, false)
      handle.dispose()
    }
  })
}

